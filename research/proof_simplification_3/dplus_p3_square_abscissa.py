"""Exact direct p=3 square-abscissa certificate on the genus-two curve D+.

This certificate proves C041 directly on

    D+: R^2 = 4*a^5 - 8*a^2 + 5*a

without classifying rational points on the genus-three double cover C3.
It replays only the D+-specific Cantor/formal-log routines already hardened
in the PR #6 implementation; no C3 residue-disk, quotient-rank, or rational-
point conclusion is imported.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import sys

import sympy as sp


ROOT = Path(
    os.environ.get("CUBOID_REPO_ROOT", Path(__file__).resolve().parents[2])
).resolve()
sys.path.insert(0, str(ROOT))

from research.proof_simplification_2 import c3_p3_chabauty as exact


DEFAULT_OUTPUT = Path(__file__).with_suffix(".json")
RANK_PATH = "research/arithmetic_geometry/product_genus2_two_descent.json"
RANK_CHECKSUM = (
    "8cd90ba46311943ac32f7d9b810994a3dbb86913fdeb11b64c8d0e1ae13c19a2"
)


class CertificateFailure(RuntimeError):
    """Raised when any proof-critical exact gate fails."""


def require(condition: object, message: str) -> None:
    """Fail closed independently of Python assertion optimization."""

    if not condition:
        raise CertificateFailure(message)


def strict_json_object(pairs: list[tuple[str, object]]) -> dict[str, object]:
    """Reject duplicate JSON keys at the dependency boundary."""

    answer: dict[str, object] = {}
    for key, value in pairs:
        require(key not in answer, f"rank artifact repeats JSON key {key!r}")
        answer[key] = value
    return answer


def checked_rank_artifact(path: Path | None = None) -> dict[str, object]:
    """Load and pin the exact rank/torsion/mod-2 certificate."""

    artifact_path = (
        Path(os.environ.get("CUBOID_DPLUS_RANK_ARTIFACT", ROOT / RANK_PATH))
        if path is None
        else Path(path)
    )
    try:
        payload = json.loads(
            artifact_path.read_text(encoding="utf-8"),
            object_pairs_hook=strict_json_object,
        )
    except CertificateFailure:
        raise
    except Exception as error:
        raise CertificateFailure("rank artifact is not valid JSON") from error
    require(isinstance(payload, dict), "rank artifact is not a JSON object")
    require(payload.get("schema") == 1, "rank artifact has the wrong schema")
    checksum = payload.get("sha256_without_checksum")
    require(checksum == RANK_CHECKSUM, "rank artifact is not the pinned version")
    canonical = dict(payload)
    del canonical["sha256_without_checksum"]
    encoded = json.dumps(canonical, sort_keys=True, separators=(",", ":")).encode()
    require(
        hashlib.sha256(encoded).hexdigest() == checksum,
        "rank artifact checksum does not verify",
    )
    require(payload.get("rank") == 1, "rank artifact does not prove rank one")
    require(
        payload.get("torsion") == "Z/2Z generated by T",
        "rank artifact has the wrong torsion conclusion",
    )
    require(
        payload.get("D_and_T_independent_mod_2") is True,
        "rank artifact does not prove D,T independence modulo 2",
    )
    require(
        payload.get("successive_local_survivor_counts")
        == {"square_norm": 512, "at_2": 64, "at_5": 8, "at_17": 4},
        "rank artifact survivor chain changed",
    )
    return payload


def square_unit_residue(residue: int) -> int:
    """Certify the nonzero residue of a 3-adic square unit."""

    require(residue in (1, 2), "unit residue must be nonzero modulo 3")
    require(residue == 1, "a 3-adic square unit cannot reduce to 2 modulo 3")
    return residue


def certify_square_disk_classification() -> dict[str, object]:
    """Classify projective p=3 disks under the square-abscissa condition."""

    a, r = sp.symbols("a r")
    f = 4 * a**5 - 8 * a**2 + 5 * a
    cofactor = sp.expand(f / a)
    require(cofactor.subs(a, 0) == 5, "wrong cofactor at a=0")
    require(int(cofactor.subs(a, 0)) % 3 == 2, "zero-disk cofactor is square")
    require(int(cofactor.subs(a, 1)) % 3 == 1, "unit-square disk has wrong RHS")
    square_unit_residue(1)

    affine_points = []
    for a_bar in range(3):
        for r_bar in range(3):
            if (r_bar * r_bar - int(f.subs(a, a_bar))) % 3 == 0:
                affine_points.append([a_bar, r_bar])
    require(
        affine_points == [[0, 0], [1, 1], [1, 2], [2, 1], [2, 2]],
        "unexpected affine points on D+(F3)",
    )
    require(sp.Poly(f, a).degree() == 5, "D+ is not in an odd-degree model")
    require(sp.Poly(f, a).LC() == 4, "unexpected leading coefficient at infinity")

    return {
        "curve": "R^2=4*a^5-8*a^2+5*a",
        "affine_Dplus_F3": affine_points,
        "non_square_unit_disks_excluded": ["(2,1)", "(2,-1)"],
        "odd_degree_projective_infinity_points": 1,
        "valuation_cases": {
            "v3(a)>0": (
                "a=0, or a is excluded: for a=u^2!=0, "
                "(R/u)^2=4*a^4-8*a+5 is 2 mod 3"
            ),
            "v3(a)=0": "a mod 3=1 and R mod 3=+/-1",
            "v3(a)<0": (
                "v3(a) is even and t=2*a^2/R has positive valuation, "
                "so the point is in the unique infinity disk"
            ),
            "projective": "the odd-degree model has one rational infinity",
        },
        "square_abscissa_disks": [
            "infinity",
            "(0,0)",
            "(1,1)",
            "(1,-1)",
        ],
    }


def certify_zero_disk(*, parameter: str = "R") -> dict[str, object]:
    """Prove that (0,0) is the only square-abscissa point in its disk."""

    require(parameter == "R", "R, not a, is the valid uniformizer at (0,0)")
    a, r = sp.symbols("a r")
    cofactor = 4 * a**4 - 8 * a + 5
    equation = r**2 - a * cofactor
    derivative = sp.diff(equation, a).subs({a: 0, r: 0})
    require(derivative == -5, "R is not certified as a local parameter")
    require(int(derivative) % 3 != 0, "local implicit derivative is not a unit")
    require(int(cofactor.subs(a, 0)) % 3 == 2, "zero-disk unit is not nonsquare")

    return {
        "center": "(0,0)",
        "uniformizer": "R",
        "implicit_derivative_d(R^2-a*g)/da": -5,
        "argument": (
            "If a=u^2 is nonzero with v3(a)>0, then "
            "(R/u)^2=g(a), while g(a)=4*a^4-8*a+5 is 2 modulo 3. "
            "This is impossible in Q3."
        ),
        "unique_square_abscissa_point": "(0,0)",
    }


def certify_infinity_disk(annihilator: dict[str, object]) -> dict[str, object]:
    """Use the rational uniformizer t=2a^2/R to isolate infinity."""

    require(
        annihilator.get("lambda_mod_27") == 7
        and annihilator.get("lambda_valuation") == 0,
        "infinity disk lacks the certified integral annihilator",
    )
    integer_lemmas = exact.certify_universal_integer_lemmas()
    require(integer_lemmas.get("status") == "PASS", "infinity tail proof failed")

    t, w, z, lam = sp.symbols("t w z lambda")
    relation = sp.expand(w - t**2 * (1 - 2 * w**3 + sp.Rational(5, 4) * w**4))
    require(relation.subs({t: 0, w: 0}) == 0, "infinity relation misses origin")
    require(
        sp.diff(relation, w).subs({t: 0, w: 0}) == 1,
        "infinity formal implicit derivative is not one",
    )
    denominators = [
        sp.denom(coefficient)
        for coefficient in sp.Poly(relation, t, w).coeffs()
    ]
    require(
        all(int(denominator) % 3 != 0 for denominator in denominators),
        "infinity implicit equation is not 3-integral",
    )

    w_series = t**2
    for _ in range(5):
        w_series = sp.series(
            t**2 * (1 - 2 * w_series**3 + sp.Rational(5, 4) * w_series**4),
            t,
            0,
            12,
        ).removeO()
    expected_w = t**2 - 2 * t**8 + sp.Rational(5, 4) * t**10
    require(sp.expand(w_series - expected_w) == 0, "wrong infinity coordinate series")

    integrand = sp.series(
        sp.cancel(t * sp.diff(w_series, t) / (2 * w_series))
        * (1 - lam * w_series),
        t,
        0,
        6,
    ).removeO()
    require(integrand.subs(t, 0) == 1, "annihilator is not a unit at infinity")
    primitive = sp.expand(sp.integrate(integrand, t))
    normalized = sp.series(
        primitive.subs({t: 3 * z, lam: 7}) / 3,
        z,
        0,
        6,
    ).removeO()
    polynomial = sp.Poly(normalized, z, domain=sp.QQ)
    reductions = {
        degree: exact.rational_residue(polynomial.coeff_monomial(z**degree), 3)
        for degree in range(1, 6)
    }
    require(reductions[1] == 1, "infinity primitive has nonunit linear term")
    require(
        all(reductions[degree] == 0 for degree in range(2, 6)),
        "unexpected low-degree infinity primitive term",
    )
    # Formal implicit-function recursion is over Z_3 because d(relation)/dw=1.
    # Thus every coefficient of eta/dt is 3-integral.  After t=3z and
    # division by 3, every primitive degree n>=2 has valuation at least
    # n-1-v3(n)>=1, the universal lemma certified above.

    return {
        "point": "infinity",
        "unique_projective_branch": True,
        "rational_uniformizer": "t=2*a^2/R",
        "inverse_coordinate": "w=1/a",
        "exact_relation": "w=t^2*(1-2*w^3+(5/4)*w^4)",
        "w_series_mod_t12": str(expected_w),
        "annihilator": "(lambda-a)*da/R",
        "annihilator_in_t": "(t/(2*w))*(1-lambda*w)*dw",
        "normalized_primitive_mod_3": "F(3*z)/3 = z mod 3",
        "universal_tail": "n-1-v3(n)>=1 for every n>=2",
        "negative_valuation": (
            "If v3(a)<0, then v3(a) is even and "
            "v3(t)=-v3(a)/2>0."
        ),
        "unique_square_abscissa_point": "infinity",
    }


def certify_a_one_disks(
    annihilator: dict[str, object],
    *,
    use_p7_saturation: bool,
) -> dict[str, object]:
    """Certify the two a=1 disks, retaining the unknown MW index."""

    require(
        use_p7_saturation,
        "the unknown Mordell-Weil index requires the p=7 3-saturation lemma",
    )
    p7 = exact.prime_7_index_audit()
    require(
        p7.get("J_F7_order") == 42
        and p7.get("D_mod_7_order") == 21
        and "3 does not divide m" in str(p7.get("conclusion")),
        "p=7 index certificate did not prove 3-saturation",
    )
    local = exact.rational_lattice_refinement(annihilator)
    records = local.get("records")
    require(isinstance(records, list) and len(records) == 2, "missing a=1 disks")
    require(
        {record.get("D_plus_center") for record in records} == {"(1,1)", "(1,-1)"},
        "wrong a=1 disk centers",
    )
    require(
        all(record.get("rational_zero") == "z=0 only" for record in records),
        "an a=1 disk has an extra rational zero",
    )
    return {
        "p7_integral_saturation": p7,
        "local_disks": records,
        "argument": (
            "D=mG with m odd and the p=7 group data give gcd(m,21)=1. "
            "Hence v3(log_0 G)=2. For Q in a disk of P=(1,+/-1), "
            "log_0[Q-P] lies in 9*Z_3; H0(a-1)=(a-1)*unit then forces "
            "a-1 in 9*Z_3. The annihilating primitive at a-1=9z is "
            "z times a unit."
        ),
        "unique_square_abscissa_points": ["(1,1)", "(1,-1)"],
    }


def verify(*, use_p7_saturation: bool = True) -> dict[str, object]:
    """Run the direct D+ square-abscissa proof and return its artifact."""

    rank = checked_rank_artifact()
    disk_classes = certify_square_disk_classification()
    mumford_u, _, eleven_d = exact.multiple_11D_data()
    annihilator = exact.annihilator_ratio(mumford_u)
    require(
        annihilator.get("D_plus_annihilator") == "(lambda-a)*da/R",
        "wrong D+ annihilating differential",
    )
    zero = certify_zero_disk()
    one = certify_a_one_disks(
        annihilator,
        use_p7_saturation=use_p7_saturation,
    )
    infinity = certify_infinity_disk(annihilator)

    a, r = sp.symbols("a r")
    rhs = 4 * a**5 - 8 * a**2 + 5 * a
    known_affine = [(0, 0), (1, 1), (1, -1)]
    require(
        all(sp.expand(r_value**2 - rhs.subs(a, a_value)) == 0
            for a_value, r_value in known_affine),
        "a known affine point is not on D+",
    )
    require(
        {a_value for a_value, _ in known_affine} == {0, 1},
        "a known abscissa is not a rational square",
    )

    payload: dict[str, object] = {
        "schema": 1,
        "target": "direct D+ square-abscissa classification",
        "status": "PASS",
        "curve": "D+: R^2=4*a^5-8*a^2+5*a",
        "rank_input": {
            "path": RANK_PATH,
            "checksum": RANK_CHECKSUM,
            "rank": rank["rank"],
            "torsion": rank["torsion"],
            "D_and_T_independent_mod_2": rank["D_and_T_independent_mod_2"],
        },
        "disk_classification": disk_classes,
        "D_plus_logarithm": {
            "multiple_11D": eleven_d,
            "annihilator": annihilator,
            "c3_geometry_used": False,
        },
        "zero_disk": zero,
        "a_one_disks": one,
        "infinity_disk": infinity,
        "known_points_checked": ["infinity", "(0,0)", "(1,1)", "(1,-1)"],
        "theorem": (
            "{P in D+(Q): a(P) is a rational square}="
            "{infinity,(0,0),(1,1),(1,-1)}"
        ),
        "dependency_change": {
            "removed": [
                "C3 rational-point classification",
                "rank E1(Q)=1",
                "Jac(C3)~E1xJac(D+) Chabauty-rank argument",
                "C3 affine and infinity disk calculations",
                "p=23 Mordell-Weil sieve",
                "p=7 square-abscissa tables",
                "p=7 formal logarithm and Coleman calculation",
            ],
            "retained": [
                "Schaefer-Stoll rank/torsion/mod-2 certificate",
                "direct p=3 D+ annihilator calculation",
                "#J(F7)=42 and ord(D mod 7)=21 for integral 3-saturation",
            ],
        },
        "implementation_hygiene": {
            "c3_theorem_or_artifact_imported": False,
            "shared_source_helpers": (
                "D+-specific exact Cantor, valuation, finite-Jacobian, "
                "and universal-tail routines from the hardened PR #6 module"
            ),
        },
        "success_level": "B",
    }
    canonical = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode()
    payload["sha256_without_checksum"] = hashlib.sha256(canonical).hexdigest()
    return payload


def main() -> None:
    """Run fail-closed and write the canonical artifact only on success."""

    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--omit-p7-saturation",
        action="store_true",
        help="negative audit mode; must fail because the MW index is unknown",
    )
    args = parser.parse_args()
    try:
        payload = verify(use_p7_saturation=not args.omit_p7_saturation)
    except Exception as error:
        print("direct D+ p=3 square-abscissa certificate: FAIL")
        print(f"{type(error).__name__}: {error}")
        raise SystemExit(1) from error
    args.output.write_text(
        json.dumps(payload, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
    )
    print("direct D+ p=3 square-abscissa certificate: PASS")
    print("square-abscissa disks: infinity, (0,0), (1,+/-1)")
    print("p=7 retained only for integral 3-saturation")
    print("C3, rank E1, and Jac(C3) decomposition are not proof inputs")
    print("wrote", args.output)


if __name__ == "__main__":
    main()
